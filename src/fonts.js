// glyphs may omit trailing empty rows (5x7 caps live in a 5x8 cell with a descender row)
function compile (tbl, w, h) {
  const g = {}
  for (const [ch, def] of Object.entries(tbl)) {
    const rows = def.split('/')
    while (rows.length < h) rows.push('0'.repeat(w))
    if (rows.length !== h || rows.some(r => r.length !== w)) throw new Error('bad glyph ' + ch)
    g[ch] = rows.map(r => r.split('').map(c => c === '1' ? 1 : 0))
  }
  return { w, h, glyphs: g }
}

export const FONTS = {
  '5x7': compile(F5, 5, 8),
  '3x5': compile(F3, 3, 5)
}

export function glyph (fontName, ch) {
  const f = FONTS[fontName]
  if (!f) throw new Error('unknown font: ' + fontName)
  return f.glyphs[ch] || f.glyphs[ch.toUpperCase()] || f.glyphs['?'] || f.glyphs[' ']
}

export function textWidth (fontName, str, spacing = 1, scale = 1) {
  const f = FONTS[fontName]
  if (!str.length) return 0
  return (str.length * f.w + (str.length - 1) * spacing) * scale
}
